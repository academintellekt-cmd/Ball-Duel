const assert=require('assert');
global.LobbyOptions=require('../lib/lobby-options');
const L=require('../public/lobby');
const names={modes:{free:'Свободная игра',targets:'Зелёные цели',values:'Ценные кольца'},difficulties:{easy:'Лёгкий',medium:'Средний',hard:'Сложный',extreme:'Экстрим'},minute:'мин'};
function view(extra){const selection=extra.selection||LobbyOptions.defaultSelection('free',[1,2,3]);const players=extra.players||[];const session=!!extra.session;return{lang:'ru',players,max:2,selection,options:LobbyOptions.modeOptions(selection.mode,[1,2,3]),names,check:LobbyOptions.canStart(selection,players,2,session),session,remainingSec:0,connected:true,overlay:null,rules:null,starting:false,startDenied:'',...extra}}
let html=L.html(view({}));
assert(html.includes('class="lobby-screen'));
assert(html.includes('BALL DUEL'));
assert.strictEqual((html.match(/data-lobby-mode="/g)||[]).length,3,'three modes');
assert.strictEqual((html.match(/class="lobby-slot empty/g)||[]).length,2);
assert(html.includes('VS'));
assert(/data-lobby-start[^>]*disabled/.test(html),'start disabled with no players');
assert(html.includes('Для дуэли нужны два игрока'));
assert(!html.includes('data-lobby-difficulty'),'free has no difficulty');
assert(html.includes('data-lobby-duration="1"')&&html.includes('data-lobby-duration="3"'));
const two=[{uid:'A',name:'Ann',avatar:'X3'},{uid:'B',name:'<b>Bob</b>',avatar:null}];
html=L.html(view({players:two}));
assert(!/data-lobby-start[^>]*disabled/.test(html));
assert(html.includes('data-lobby-remove="A"'));
assert(html.includes('&lt;b&gt;Bob&lt;/b&gt;'));
assert(html.includes('hex-cyan'),'X3 avatar is the cyan diamond');
assert(html.includes('hex-orange'),'slot 2 without avatar is orange');
html=L.html(view({players:two,selection:{mode:'values',variant:null,difficulty:'hard',durationMinutes:2}}));
assert.strictEqual((html.match(/data-lobby-difficulty="/g)||[]).length,4);
assert(html.includes('Ценные кольца · Сложный · 2 мин'));
html=L.html(view({players:two,session:true,remainingSec:125}));
assert(!html.includes('data-lobby-remove'));
assert(html.includes('data-action="leaders"')&&html.includes('Рекорды'));
assert(html.includes('data-action="session-exit"')&&html.includes('Завершить'));
assert(html.includes('2:05'));
assert(!/data-lobby-start[^>]*disabled/.test(html),'session start is enabled');
html=L.html(view({overlay:{type:'denied',reason:'offline'}}));
assert(html.includes('Нет связи с сервером'));
html=L.html(view({overlay:{type:'checking'}}));
assert(html.includes('Проверяем браслет'));
html=L.html(view({overlay:{type:'rules',mode:'values'},rules:{title:'Ценные кольца',lead:'Цвет кольца определяет очки',steps:['шаг 1','шаг 2'],demoHtml:'<div class="info-rings"></div>'}}));
assert(html.includes('Как играть')&&html.includes('Цвет кольца определяет очки')&&html.includes('<li>шаг 2</li>')&&html.includes('info-rings')&&html.includes('Понятно'));
html=L.html(view({overlay:{type:'idle'}}));
assert(html.includes('Вы ещё здесь?')&&html.includes('data-lobby-idle="no"'));
html=L.html(view({players:two,overlay:{type:'confirmRemove',uid:'A'}}));
assert(html.includes('Убрать игрока?')&&html.includes('data-lobby-confirm="yes"'));
html=L.html(view({connected:false}));
assert(html.includes('Нет связи с Gateway'));
html=L.html(view({players:two,startDenied:'not_enough_players'}));
assert(html.includes('Ждём второго игрока'));
for(const lang of['ru','en','de','fr','zh','ja']){const s=L.strings(lang);for(const key of Object.keys(L.strings('en')))assert(s[key],`${lang}.${key}`)}
html=L.html(view({overlay:{type:'denied',reason:'unregistered'}}));
assert(html.includes('Данный браслет не найден в системе. Обратитесь к администратору.'),'Lava Jump wording for an unknown wristband');
// Lobby profile window.
const duo=[{uid:'A',name:'Алекс',avatar:'X1'},{uid:'B',name:'Мира',avatar:'X2'}];
html=L.html(view({players:duo}));
assert(html.includes('data-lobby-profile="A"')&&html.includes('data-lobby-profile="B"'),'player cards open the profile');
const data={username:'Алекс',level:3,xp_in_level:120,needed_xp:500,time_started:true,remaining_seconds:125,records:[{mode_id:'values',level_id:'hard:2',best_score:42},{mode_id:'free',level_id:'-:1',best_score:17}],recent:[]};
html=L.html(view({players:duo,overlay:{type:'profile',uid:'A',state:'ready',data}}));
assert(html.includes('Уровень 3')&&html.includes('2:05'),'level and time');
assert(html.includes('Ценные кольца · Сложный · 2 мин')&&html.includes('Свободная игра · 1 мин'),'records name mode, difficulty and time');
assert(html.includes('data-lobby-profile-remove="A"')&&html.includes('Закрыть'),'remove and close');
html=L.html(view({players:duo,session:true,overlay:{type:'profile',uid:'A',state:'ready',data}}));
assert(!html.includes('data-lobby-profile-remove'),'no removing a player during a paid session');
// Queue for the next game.
{
  const q=o=>({lang:'ru',state:'none',players:[],max:2,remainingSec:null,canOpen:true,...o});
  const kim={uid:'K',name:'kim',avatar:'X1'},lee={uid:'L',name:'lee',avatar:'X2'};
  let h=L.queue(q({}));
  assert(h.includes('data-action="queue-open"')&&h.includes('Встать в очередь')&&!h.includes('queue-cancel'),'none + canOpen -> join button only');
  assert.strictEqual(L.queue(q({canOpen:false})),'','none + !canOpen -> empty');
  assert.strictEqual(L.queue(null),'','no queue -> empty');
  h=L.queue(q({state:'collecting',players:[kim],remainingSec:25}));
  assert(h.includes('Приложите браслеты')&&h.includes('kim')&&h.includes('1 / 2')&&h.includes('0:25')&&h.includes('data-action="queue-done"')&&h.includes('data-action="queue-cancel"'),'collecting');
  h=L.queue(q({state:'collecting',players:[]}));
  assert(!h.includes('queue-done')&&h.includes('queue-cancel')&&h.includes('0 / 2'),'no Done without a bracelet');
  h=L.queue(q({state:'waiting',players:[kim,lee]}));
  assert(h.includes('Следующие: kim и lee')&&h.includes('data-action="queue-cancel"')&&h.includes('Выйти из очереди')&&!h.includes('lobby-queue-slot')&&!h.includes('queue-done'),'waiting');
  h=L.queue(q({state:'reserved',players:[kim,lee],remainingSec:42}));
  assert(h.includes('Следующие: kim и lee — приложите браслет')&&h.includes('42'),'reserved');
  assert(L.queue(q({lang:'en',state:'waiting',players:[kim,lee]})).includes('Up next: kim and lee'),'en names joined with and');
  h=L.queue(q({state:'waiting',players:[{uid:'X',name:'<img src=x>'}]}));
  assert(!h.includes('<img')&&h.includes('&lt;img src=x&gt;'),'names are escaped');
  assert(L.queue(q({lang:'de'})).includes('Join the queue'),'de falls back to en');
  assert(L.html(view({overlay:{type:'denied',reason:'busy'}})).includes('Аттракцион занят — нажмите «Встать в очередь»'),'denied busy');
  assert(L.html(view({overlay:{type:'denied',reason:'reserved'}})).includes('Место занято следующими'),'denied reserved');
  html=L.html(view({queue:q({state:'waiting',players:[kim]})}));
  assert(html.includes('Следующие')&&html.indexOf('lobby-queue')<html.indexOf('lobby-launch'),'lobby html embeds the queue bar above the launch block');
  assert(!L.html(view({})).includes('lobby-queue'),'no queue, no bar');
  html=L.html(view({queue:q({state:'reserved',players:[kim]})}));
  assert(html.includes('Приложите браслеты')&&!html.includes('Прислони браслет'),'reserved + empty lobby: call for the queued');
  html=L.html(view({queue:q({state:'waiting',players:[kim]})}));
  assert(html.includes('Прислони браслет'),'waiting keeps the usual call');
}
console.log('lobby-view tests passed');
